import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {createMetrics,watchStream} from './metrics-local.mjs';
import {PassThrough} from 'node:stream';

const m=createMetrics(),sensitive='FAKE_PASSWORD_TOKEN';
assert.equal(m.result().estado,'sin_datos');
for(let i=0;i<19;i++)m.consume(JSON.stringify({event:'api.request',route:'/api/v1/news',method:'GET',status:200,durationMs:100,extra:sensitive}));
m.consume(JSON.stringify({event:'api.request',route:'/api/v1/news/[id]/participation',method:'POST',status:503,durationMs:1000}));
m.consume(JSON.stringify({event:'api.request',route:'/api/v1/news',method:'GET',status:429,durationMs:20}));
m.consume(JSON.stringify({event:'worker.job',type:'source.fetch',status:'failed',durationMs:4,secret:sensitive}));
m.consume(JSON.stringify({event:'worker.scheduler',status:'failed'}));
m.consume(JSON.stringify({event:'api.request',route:sensitive,method:'GET',status:200,durationMs:0}));
m.consume('{malformed');
const report=m.result();
assert.equal(report.estado,'requiere_revision');
assert.equal(report.api.total,21);
assert.equal(report.api.erroresServidor,1);
assert.equal(report.api.limitadas,1);
assert.equal(report.api.desde1000ms,1);
assert.deepEqual(report.api.p95IntervaloMs,{mayorQueMs:null,hastaMs:100});
assert.equal(report.confirmaciones.erroresServidor,1);
assert.equal(report.worker.fallidos,1);
assert.equal(report.worker.agendaFallida,1);
assert.equal(report.lineasIgnoradas,2);
assert(!JSON.stringify(report).includes(sensitive));
const input=[JSON.stringify({event:'api.request',route:'/api/v1/news',method:'GET',status:200,durationMs:12}),sensitive].join('\n');
const child=spawnSync(process.execPath,['scripts/metrics-local.mjs'],{input,encoding:'utf8',windowsHide:true});
assert.equal(child.status,0);const output=JSON.parse(child.stdout);
assert.equal(output.estado,'sin_alertas_detectadas');
assert.equal(output.lineasIgnoradas,1);
assert(!child.stdout.includes(sensitive));
console.log('Z12 métricas: agregación, umbrales, entrada vacía y privacidad OK');

const stream=new PassThrough(),windows=[];
const watched=watchStream(stream,{intervalMs:40,emit:event=>windows.push(event)});
stream.write(JSON.stringify({event:'api.request',route:'/api/v1/news',method:'GET',status:503,durationMs:7,secret:sensitive})+'\n');
await new Promise(resolve=>setTimeout(resolve,100));
stream.end(JSON.stringify({event:'worker.job',type:'source.fetch',status:'failed',durationMs:2,secret:sensitive})+'\n');
await watched;
assert(windows.some(x=>x.tipo==='intervalo'&&x.api?.erroresServidor===1&&x.alertas.includes('RESPUESTAS_API_5XX')));
assert(windows.some(x=>x.tipo==='intervalo'&&x.estado==='sin_datos'));
assert.equal(windows.at(-1).tipo,'entrada_finalizada');
assert.equal(windows.at(-1).worker.fallidos,1);
assert(!JSON.stringify(windows).includes(sensitive));
const live=spawnSync(process.execPath,['scripts/metrics-local.mjs','--vigilar'],{input,encoding:'utf8',windowsHide:true});
assert.equal(live.status,0);
assert.equal(JSON.parse(live.stdout).tipo,'entrada_finalizada');
assert(!live.stdout.includes(sensitive));
console.log('Z12 vigilancia local: intervalos, fallos, ausencia de datos y cierre OK');
