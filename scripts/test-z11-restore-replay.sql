begin;
set local role riuya_purge_executor;
grant execute on function private.begin_account_purge(uuid,uuid),private.purge_account_contributions(uuid,uuid),private.purge_editorial_references(uuid,uuid),private.prepare_account_auth_purge(uuid,uuid),private.finish_account_purge(uuid,uuid) to postgres;
reset role;
do $$
declare u uuid:=gen_random_uuid();v uuid:=gen_random_uuid();rid uuid:=gen_random_uuid();sid uuid:=gen_random_uuid();otherjob uuid:=gen_random_uuid();job jsonb;jid uuid;tok uuid;value record;
begin
 if has_function_privilege('authenticated','private.restore_begin_purge(uuid,uuid)','execute') or has_function_privilege('riuya_worker_local','private.restore_begin_purge(uuid,uuid)','execute') then raise exception 'RESTORE_EXPOSED';end if;
 insert into auth.users(id,email) values(u,'z11-replay-'||u||'@example.invalid'),(v,'z11-replay-'||v||'@example.invalid');
 insert into private.profiles(id,account_status) values(u,'active'),(v,'active');
 insert into auth.sessions(id,user_id,created_at) values(sid,u,now());
 insert into private.jobs(id,job_type,payload,dedupe_key,created_by) values(otherjob,'draft.generate','{}','z11-replay-'||otherjob,v);
 perform set_config('role','riuya_restore_client',true);
 job:=private.restore_begin_purge(u,rid);jid:=(job->>'id')::uuid;tok:=(job->>'leaseToken')::uuid;
 perform set_config('role','none',true);
 if (select account_status from private.profiles where id=u)<>'deletion_pending' or exists(select 1 from auth.sessions where id=sid) or (select status from private.jobs where id=otherjob)<>'queued' then raise exception 'RESTORE_SCOPE_FAILED';end if;
 perform set_config('role','riuya_restore_client',true);
 begin perform private.restore_begin_purge(u,rid);raise exception 'NEW_LEASE_STOLEN';exception when raise_exception then if sqlerrm<>'RESTORE_IN_PROGRESS' then raise;end if;end;
 perform set_config('role','none',true);
 update private.jobs set lease_until=clock_timestamp()-interval '1 second' where id=jid;
 perform set_config('role','riuya_restore_client',true);job:=private.restore_begin_purge(u,rid);perform set_config('role','none',true);
 if (job->>'id')::uuid<>jid or (job->>'leaseToken')::uuid=tok then raise exception 'EARLY_RESUME_FAILED';end if;
 tok:=(job->>'leaseToken')::uuid;
 perform private.begin_account_purge(jid,tok);
 perform set_config('role','riuya_restore_client',true);
 begin perform private.restore_begin_purge(u,rid);raise exception 'ACTIVE_LEASE_STOLEN';exception when raise_exception then if sqlerrm<>'RESTORE_IN_PROGRESS' then raise;end if;end;
 perform set_config('role','none',true);
 update private.jobs set lease_until=clock_timestamp()-interval '1 second' where id=jid;
 perform set_config('role','riuya_restore_client',true);job:=private.restore_begin_purge(u,rid);perform set_config('role','none',true);
 if (job->>'id')::uuid<>jid or (job->>'leaseToken')::uuid=tok then raise exception 'RESUME_FAILED';end if;
 tok:=(job->>'leaseToken')::uuid;
 perform private.purge_account_contributions(jid,tok);perform private.purge_editorial_references(jid,tok);perform private.prepare_account_auth_purge(jid,tok);
 delete from auth.users where id=u;
 perform set_config('role','riuya_restore_auditor',true);
 select * into value from private.restore_purge_audit(array[u]);
 if value.auth_present or value.profile_present or not value.pending_purge then raise exception 'PENDING_AUTH_GAP_MISSED';end if;
 perform set_config('role','none',true);
 update private.jobs set lease_until=clock_timestamp()-interval '1 second' where id=jid;
 perform set_config('role','riuya_restore_client',true);job:=private.restore_begin_purge(u,rid);perform set_config('role','none',true);
 tok:=(job->>'leaseToken')::uuid;
 if not private.finish_account_purge(jid,tok) then raise exception 'RESUME_FINALIZE_FAILED';end if;
 if not exists(select 1 from auth.users where id=v) or (select status from private.jobs where id=otherjob)<>'queued' then raise exception 'OTHER_DATA_LOST';end if;
end $$;
rollback;
