import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {randomBytes,randomUUID} from 'node:crypto';
import {mkdtemp,mkdir,readFile,writeFile,unlink,rmdir,readdir,lstat} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {initializePurgeJournal,initializePurgeCheckpoint,recordPurgeIntent} from '../src/worker/purge-journal.mjs';
import {createCustodyBackup,verifyCustodyBackup,restoreCustodyBackup} from '../src/worker/purge-custody-backup.mjs';

const root=await mkdtemp(join(tmpdir(),'riuya-backup-custody-')),dir=join(root,'journal');await mkdir(dir);
const journal={dir,key:randomBytes(32),anchorPath:join(root,'anchor'),checkpointPath:join(root,'checkpoint')},keyPath=join(root,'key'),output=join(root,'backup.riuya'),damaged=join(root,'damaged.riuya');
const env={RIUYA_PURGE_JOURNAL_DIR:dir,RIUYA_PURGE_JOURNAL_KEY_FILE:keyPath,RIUYA_PURGE_JOURNAL_ANCHOR_FILE:journal.anchorPath,RIUYA_PURGE_CHECKPOINT_FILE:journal.checkpointPath};
const password='fixture-'+randomUUID(),userId=randomUUID(),requestId=randomUUID();
const recovered=join(root,'recovered'),staleDir=join(root,'stale'),recoveredKey=join(root,'recovered.key'),recoveredAnchor=join(root,'recovered.anchor'),staleKey=join(root,'stale.key'),staleAnchor=join(root,'stale.anchor'),badDir=join(root,'bad'),badCheckpoint=join(root,'bad.checkpoint'),badKey=join(root,'bad.key'),badAnchor=join(root,'bad.anchor');
try{
 await initializePurgeJournal(journal);await initializePurgeCheckpoint(journal);await writeFile(keyPath,journal.key.toString('hex'),{flag:'wx'});
 await recordPurgeIntent({...journal,requestId,userId,requireCheckpoint:true});
 let checks=0;
 const result=await createCustodyBackup({env,path:output,passphrase:password,verifyStorage:()=>{checks++;}});
 assert.equal(checks,2);assert.deepEqual(result,{recorded:1});
 const archive=await readFile(output),text=archive.toString('utf8');
 assert.ok(!text.includes(userId)&&!text.includes(requestId)&&!text.includes(password)&&!text.includes(journal.key.toString('hex')));
 assert.deepEqual(await verifyCustodyBackup({path:output,passphrase:password}),{recorded:1});
 await assert.rejects(()=>verifyCustodyBackup({path:output,passphrase:'frase-incorrecta-123456789'}),/PURGE_BACKUP_INVALID/);
 await assert.rejects(()=>createCustodyBackup({env,path:output,passphrase:password,verifyStorage:()=>{}}),/PURGE_BACKUP_WRITE_FAILED/);
 assert.deepEqual(await readFile(output),archive);
 const changed=JSON.parse(text),bytes=Buffer.from(changed.ciphertext,'base64url');bytes[0]^=1;changed.ciphertext=bytes.toString('base64url');
 await writeFile(damaged,JSON.stringify(changed),{flag:'wx'});
 await assert.rejects(()=>verifyCustodyBackup({path:damaged,passphrase:password}),/PURGE_BACKUP_INVALID/);
 await assert.rejects(()=>createCustodyBackup({env,path:join(dir,'backup'),passphrase:password,verifyStorage:()=>{}}),/PURGE_BACKUP_CONFIG_INVALID/);
 await mkdir(badDir);
 await writeFile(badCheckpoint,'{', {flag:'wx'});
 const badEnv={RIUYA_PURGE_JOURNAL_DIR:badDir,RIUYA_PURGE_JOURNAL_KEY_FILE:badKey,RIUYA_PURGE_JOURNAL_ANCHOR_FILE:badAnchor,RIUYA_PURGE_CHECKPOINT_FILE:badCheckpoint};
 await assert.rejects(()=>restoreCustodyBackup({env:badEnv,path:output,passphrase:'frase-incorrecta-123456789',verifyStorage:()=>{}}),/PURGE_BACKUP_INVALID/);
 assert.deepEqual(await readdir(badDir),[]);
 await assert.rejects(()=>restoreCustodyBackup({env:badEnv,path:output,passphrase:password,verifyStorage:()=>{}}),/PURGE_BACKUP_CHECKPOINT_INVALID/);
 assert.deepEqual(await readdir(badDir),[]);
 await assert.rejects(()=>lstat(badKey),error=>error.code==='ENOENT');
 await mkdir(recovered);
 const recoveryEnv={RIUYA_PURGE_JOURNAL_DIR:recovered,RIUYA_PURGE_JOURNAL_KEY_FILE:recoveredKey,RIUYA_PURGE_JOURNAL_ANCHOR_FILE:recoveredAnchor,RIUYA_PURGE_CHECKPOINT_FILE:journal.checkpointPath};
 const checkpointBefore=await readFile(journal.checkpointPath);
 assert.deepEqual(await restoreCustodyBackup({env:recoveryEnv,path:output,passphrase:password,verifyStorage:()=>{}}),{recorded:1});
 assert.deepEqual(await readFile(join(recovered,'purges.ndjson')),await readFile(join(dir,'purges.ndjson')));
 assert.equal((await readFile(recoveredKey,'utf8')).trim(),(await readFile(keyPath,'utf8')).trim());
 assert.deepEqual(await readFile(recoveredAnchor),await readFile(journal.anchorPath));
 assert.deepEqual(await readFile(journal.checkpointPath),checkpointBefore);
 await assert.rejects(()=>restoreCustodyBackup({env:recoveryEnv,path:output,passphrase:password,verifyStorage:()=>{}}),/PURGE_JOURNAL_ALREADY_EXISTS/);
 await recordPurgeIntent({...journal,requestId:randomUUID(),userId:randomUUID(),requireCheckpoint:true});
 await mkdir(staleDir);
 const staleEnv={...recoveryEnv,RIUYA_PURGE_JOURNAL_DIR:staleDir,RIUYA_PURGE_JOURNAL_KEY_FILE:staleKey,RIUYA_PURGE_JOURNAL_ANCHOR_FILE:staleAnchor};
 await assert.rejects(()=>restoreCustodyBackup({env:staleEnv,path:output,passphrase:password,verifyStorage:()=>{}}),/PURGE_BACKUP_STALE/);
 assert.deepEqual(await readdir(staleDir),[]);
 await assert.rejects(()=>lstat(staleKey),error=>error.code==='ENOENT');
 const cli=spawnSync(process.execPath,['scripts/custody-backup.mjs','verificar',output],{encoding:'utf8',windowsHide:true});
 assert.equal(cli.status,1);assert.match(cli.stderr,/PURGE_BACKUP_TTY_REQUIRED/);
 console.log('Z11 custodia: copia cifrada, recuperación, copia antigua y no sobrescritura: OK');
}finally{
 for(const path of [output,damaged,keyPath,journal.anchorPath,journal.checkpointPath,join(dir,'purges.ndjson'),join(recovered,'purges.ndjson'),recoveredKey,recoveredAnchor,staleKey,staleAnchor,badCheckpoint,badKey,badAnchor])await unlink(path).catch(()=>{});
 await rmdir(recovered).catch(()=>{});await rmdir(staleDir).catch(()=>{});await rmdir(badDir).catch(()=>{});await rmdir(dir);await rmdir(root);
}
